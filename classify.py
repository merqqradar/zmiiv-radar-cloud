# Рекламные хвосты, которыми каналы заканчивают почти каждый пост.
# Без вырезки они лезут в текст уведомления и ломают дедупликацию.
PROMO_PATTERNS = [
    r"https?://\S+",
    r"\[[^\]]*\]\([^)]*\)",          # markdown-ссылки целиком
    r"підпишись[^\n]*",
    r"підписатися[^\n]*",
    r"подписаться[^\n]*",
    r"надіслати новину[^\n]*",
    r"канал зі стрімами[^\n]*",
    r"канал со стримами[^\n]*",
    r"tlkinst[^\n]*",
    r"monobank[^\n]*",
    r"донат[^\n]*",
    r"@\w+",
]
PROMO_RE = re.compile("|".join(PROMO_PATTERNS), re.IGNORECASE)

NON_WORD_RE = re.compile(r"[^\w\s]", re.UNICODE)
SPACES_RE = re.compile(r"\s+")

# Сообщения длиннее этого — сводки («за минулу добу…»), а не оперативка.
# Они задевают десяток НП сразу и выше MEDIUM подниматься не должны.
DIGEST_LEN = 400

# Ретроспективные сводки: «за минулу добу», «упродовж доби», отчёты
# Генштаба и ОВА. Они перечисляют, что УЖЕ было, часто по всей области
# и с большими числами («88 БпЛА»). Такое сообщение не должно ни будить,
# ни считаться массовой угрозой: это статистика, а не предупреждение.
DIGEST_MARKERS = [
    "минулої доби", "минулу добу", "упродовж доби", "протягом доби",
    "протягом минулої", "за минулые сутки", "за прошедшие сутки",
    "за добу", "за сутки", "від початку доби", "с начала суток",
    "бойових зіткнень", "боевых столкновений", "зведення", "сводка",
    "ворог активно застосовував", "враг активно применял",
    "зазнали ударів", "підсумки", "итоги", "статистика",
    "генштаб", "оперативна інформація", "оперативная информация",
]


def has_digest_marker(body: str) -> bool:
    """Є явний маркер добової зведення («протягом минулої доби», «зведення»).

    Строгіше за is_digest(): там достатньо бути довгим (400+ символів),
    а довгим буває й свіжий репортаж про удар по сусідньому селищі —
    його губити не можна.
    """
    low = body.lower()
    return any(m in low for m in DIGEST_MARKERS)


def is_digest(body: str) -> bool:
    """Ретроспективная сводка, а не оперативное предупреждение."""
    low = body.lower()
    if any(m in low for m in DIGEST_MARKERS):
        return True
    return len(body) > DIGEST_LEN

# Посты про відбій устроены так:
#   "🟡 Богодухівський район - відбій ... Зверніть увагу, повітряна тривога
#    досі триває в: Чугуївський район, ..."
# Голова — про кого отбой, хвост — где тревога ПРОДОЛЖАЕТСЯ.
# Без отрезания хвоста отбой по чужому району читается как отбой у нас.
TAIL_MARKERS = ["зверніть увагу", "досі триває", "все ще триває",
                "обратите внимание", "тревога продолжается"]


def alert_head(body: str) -> str:
    """Отрезает хвост со списком районов, где тревога продолжается."""
    low = body.lower()
    cut = len(body)
    for marker in TAIL_MARKERS:
        pos = low.find(marker)
        if pos != -1:
            cut = min(cut, pos)
    return body[:cut]


def clean(text: str) -> str:
    """Убирает ссылки и рекламные хвосты, оставляет суть."""
    t = PROMO_RE.sub(" ", text)
    t = SPACES_RE.sub(" ", t)
    return t.strip(" \n\t·|—-")


def clean_lines(text: str) -> str:
    """Як clean(), але переноси рядків ЗБЕРІГАЮТЬСЯ.

    Канали пишуть списком, по одному пункту в рядок. clean() зліплює все
    в один рядок, і розбір на пункти втрачає межі: заголовок «Наразі в
    області 3 шахеди» прилипав до першого пункту. Тут рядки живі.
    """
    t = PROMO_RE.sub(" ", text)
    t = re.sub(r"[^\S\n]+", " ", t)
    t = re.sub(r"\s*\n\s*", "\n", t)
    return t.strip(" \n\t·|—-")


def dedup_key(level: str, places: list, threat_names: list, clean_text: str) -> str:
    """Ключ склейки дублей.

    Одно событие приходит из 3-4 каналов разными словами — склеиваем
    по смыслу: уровень + набор НП + типы угроз. Если ни НП, ни угроза
    не определились, падаем на нормализованный текст.
    """
    if places or threat_names:
        base = f"{level}|{'/'.join(sorted(set(places)))}|{'/'.join(sorted(set(threat_names)))}"
    else:
        norm = SPACES_RE.sub(" ", NON_WORD_RE.sub("", clean_text.lower()))
        base = f"{level}|{norm[:120]}"
    return hashlib.sha1(base.encode("utf-8")).hexdigest()[:16]


# Нове формулювання районних оголошень: колір + рівень небезпеки
# додано прямо в текст тривоги — «Чугуївський район — повітряна
# тривога, жовтий рівень: Дронова загроза (жовтий рівень)». Це те саме
# оголошення тривоги ПО РАЙОНУ, яке alarm_state() нижче й так розбирає
# по маркеру «повітряна тривога» — просто з кольором і типом у дужках.
# Без цієї перевірки classify() читав «Дронова загроза»/«Ракетна
# загроза» як окрему РЕАЛЬНУ ціль і слав зайве сповіщення поверх уже
# тихого оголошення тривоги.
ALARM_LEVEL_RE = re.compile(
    r"(?:тривога|тревога)\s*,\s*(?:жовтий|червоний|зелений|жёлтый|"
    r"желтый|красный|зелёный|зеленый)\s*(?:рівень|уровень)\s*[:：]",
    re.IGNORECASE)


def is_alarm_level_announcement(text: str) -> bool:
    """Районне оголошення тривоги нового зразка (з кольором/рівнем)."""
    body = clean(text)
    if not body:
        return False
    return bool(ALARM_LEVEL_RE.search(body))


