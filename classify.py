def oblast_summary(text: str):
    """Скільки цілей в області зараз. Повертає (короткий опис, всього) або None."""
    body = clean(text)
    if not body or is_digest(body):
        return None
    low = body.lower()
    if not any(h in low for h in OBLAST_HINT):
        return None

    total, kind = 0, ""
    for match in COUNT_RE.finditer(low):
        value = int(match.group(1))
        if value > total:
            total, kind = value, match.group(2)
    if total < 2:
        return None

    # «10 × шахед» — так не потрібно узгоджувати відмінки
    names = {"шахед": "шахед", "реактив": "шахед", "бпла": "БпЛА",
             "дрон": "дрон", "ракет": "ракета", "ціл": "ціль",
             "цел": "ціль", "каб": "КАБ", "бандерол": "шахед",
             "fpv": "FPV", "фпв": "FPV", "ланцет": "«Ланцет»",
             "мопед": "шахед"}
    return (f"{total} × {names.get(kind, 'ціль')}", total)


