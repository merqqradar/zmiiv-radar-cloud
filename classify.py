def civil_state(text: str):
    """Інша загроза: світло, вода, газ, хімія, ДРГ, радіація.

    Повертає (емодзі, назва, чи зі звуком, текст) або None.

    Географія суворіша, ніж для повітряних загроз: потрібне саме наше
    місто, сусіднє село або наш район. Відключення світла в Сумах чи
    в іншому районі Харківщини нас не стосується. Виняток — хімічна
    та радіаційна загроза: вони небезпечні на всю область.
    """
    body = clean(text)
    if not body:
        return None
    low = body.lower()

    near = geo.find_main(low) or bool(geo.find_close(low)) or geo.find_district(low)
    if not near:
        # Далі проходять лише хімія, радіація й масштабне світло —
        # і лише по нашій області. Усі наші канали пишуть виключно про
        # Харківщину, тому голе «по області» без слова «Харків» теж
        # рахуємо своїм (як і для ракет в OBLAST_HINT) — інакше
        # «у всій області зник світло» від наших же каналів відкидалося б.
        if not (geo.find_oblast(low) or any(h in low for h in OBLAST_HINT)):
            return None
    if geo.mentions_other_region(low) and not near:
        return None
    if not near and any(city in low for city in BIG_CITIES):
        return None

    for markers, emoji, name, loud in CIVIL:
        if not any(m in low for m in markers):
            continue
        if any(bad in low for bad in CIVIL_EXCLUDE.get(name, [])):
            continue                       # слово є, але контекст не той

        if name == "Світло":
            if any(bad in low for bad in LIGHT_SKIP):
                continue                   # ремонт, скасування, район Харкова
            big = any(m in low for m in LIGHT_SCALE)
            if not (near or (big and geo.find_oblast(low))):
                continue                   # ні в нас, ні масштабне
            if big and not near:
                name = "Світло по області"
        elif not near and name not in ("Радіаційна загроза", "Хімічна загроза"):
            continue                       # вода/газ — лише поруч

        return (emoji, name, loud, body)
    return None


