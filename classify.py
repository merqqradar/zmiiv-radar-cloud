def explain_boom(text: str):
    """Пояснення вибуху заднім числом. Повертає підпис або None.

    Потрібно для звіту: «прильотів 2» без пояснення перевірити ніяк, а
    насправді один із них міг бути розмінуванням, збиттям цілі над
    селом чи взагалі звуком прольоту. Радар не стверджує — він каже
    «можливо» і дає посилання, щоб ви звірили самі.
    """
    body = clean(text)
    if not body:
        return None
    low = body.lower()
    for label, markers in BOOM_EXPLAIN:
        if markers == "__ppo__":
            if _ppo_work(low):
                return label
            continue
        if any(m in low for m in markers):
            return label
    return None


