def oblast_rockets(text: str):
    """Ракети в області. Повертає (скільки, тип) або None."""
    body = clean(text)
    if not body or is_digest(body):
        return None
    low = body.lower()
    # «в області» без уточнення в наших каналах — це Харківщина
    if not (any(h in low for h in OBLAST_HINT) or geo.find_oblast(low)
            or geo.find_district(low) or geo.find_close(low)
            or geo.find_zmiiv(low)):
        return None

    if any(m in low for m in GONE_ELSEWHERE):
        return None            # ракети пішли в іншу область

    kinds = [n for n, _e in threats.detect_threats(low) if n in ROCKET_TYPES]
    if not kinds:
        return None

    count = 0
    for match in COUNT_RE.finditer(low):
        count = max(count, int(match.group(1)))
    # Попереджаємо лише про підтверджену кількість: більше двох.
    # Одна-дві ракети в області — це фон, у нас їх щодня кілька.
    if count < 3:
        return None
    return (count, kinds[0])


def _line_state(line: str):
    """Тревога или отбой по одной строке объявления."""
    if any(m in line for m in ALARM_OFF):
        return ("off", None)
    for marker, kind in ALARM_ON:
        if marker in line:
            return ("on", kind)
    return None


def alarm_state(text: str):
    """Разбирает объявление воздушной тревоги по нашему району.

    Возвращает ("on", вид тревоги) | ("off", None) | None.
    Это НЕ уведомление: тревога по области сама по себе в канал не шлётся,
    она только меняет закреплённое сообщение.

    Часть каналов шлёт несколько районів одним повідомленням:
        🔴 14:58, Куп'янський район - повітряна тривога!
        🔴 14:58, Чугуївський район - повітряна тривога!
    Поэтому разбираем по частям и смотрим только ту, где назван наш район.
    Иначе отбой по чужому району снимал бы нашу тревогу.
    """
    body = clean(text)
    if not body:
        return None

    # Хвост со списком районов, где тревога продолжается, — не объявление
    head = alert_head(body)

    # Части сводного сообщения, где назван именно наш район или вся область
    ours = [part for part in re.split(r"[\n\r🔴🟢🟡🚨❗]+", head)
            if part.strip() and geo.is_our_alarm_area(part.lower())]

    if ours:
        # Берём последнюю подходящую: в сводном сообщении она свежее
        for part in reversed(ours):
            state = _line_state(part.lower())
            if state:
                return state
        return None

    low = head.lower()
    if not geo.is_our_alarm_area(low):
        return None
    return _line_state(low)


def classify(text: str) -> dict | None:
    """Разбирает сообщение. None — если оно нас не касается."""
    body = clean(text)
    if not body:
        return None
    low = body.lower()

    # Для географии смотрим только «голову» сообщения: хвост со списком
    # районов, где тревога продолжается, к адресату отбоя не относится.
    geo_low = alert_head(body).lower()

    # Новина про удар ПО ворогу («СБУ вночі вдарили по базі рф у
    # Новоросійську») — не загроза Змієву. Такі дописи повні слів
    # «ракета», «Калібр», «удар», і будь-який випадковий збіг назви
    # робив з новини червону тривогу. Наше місто в тексті — виняток:
    # тоді це вже не новина про ворога, і розбираємо як звичайно.
    if config.SMART_READ and reader.foreign_strike(body):
        return None

    # Районне оголошення тривоги з кольором/рівнем («...тривога, жовтий
    # рівень: Дронова загроза...») — це не окрема реальна ціль, а сама
    # тривога; alarm_state() її й так розбирає окремо (тихо, в
    # закріплене). Якщо в тексті прямо НЕ названо Зміїв чи найближчі
    # села — не робимо з кольору/типу тривоги вигаданого сповіщення
    # про конкретний БпЛА/ракету.
    if (is_alarm_level_announcement(text)
            and not geo.find_zmiiv(low) and not geo.find_close(low)):
        return None

    # Планові підривні роботи перевіряємо найпершими: у такому
    # повідомленні є і «вибух», і назва району, і без цієї перевірки
    # воно читається як приліт.
    # Проліт балістики над областю — гуркіт, а не загроза
    if transit_state(text):
        return {
            "level": "INFO", "reason": "проліт балістики над областю",
            "places": ["Харківщина"], "threats": [], "text": body,
            "confidence": "high", "main_city": False, "near_home": False,
            "key": dedup_key("INFO", ["Харківщина"], ["проліт"], body),
        }

    # Робота ППО у ворога («у них», Бєлгород...) — не наші звуки, а
    # ознака можливого пуску ракет впереміш. Перевіряємо ДО friendly_state,
    # бо той самий вираз «работа пво» інакше зчитався б як «наша ППО».
    if enemy_pvo_state(text):
        return {
            "level": "INFO",
            "reason": "можлива підготовка пуску: працює ППО у ворога",
            "places": ["Харківщина"] if (geo.find_oblast(low)
                                         or any(h in low for h in OBLAST_HINT))
                     else [],
            "threats": [], "text": body, "confidence": "medium",
            "main_city": False, "near_home": False, "watch": True,
            "key": dedup_key("INFO", ["ворог-ппо"], ["ворог-ппо"], body),
        }

    planned = planned_works(text) if config.FILTER_PLANNED else None
    if planned:
        places = ([geo.main_name()] if geo.find_zmiiv(low) else []) \
            + geo.find_close(low)
        if not (places or geo.find_district(low) or geo.find_oblast(low)):
            return None
        return {
            "level": "INFO",
            "reason": "планові підривні роботи",
            "places": places or ["Харківщина"],
            "threats": [],
            "text": body,
            "confidence": "high",
            "main_city": bool(places and geo.main_name() in places),
            "near_home": bool(places or geo.find_district(low)),
            "key": dedup_key("INFO", places, ["планові роботи"], body),
        }

    # «Звуки наші» и робота ППО — окрема гілка: географія тут м'якша,
    # такі повідомлення часто приходять без назви населеного пункту.
    friendly = friendly_state(text)

    zmiiv = geo.find_main(geo_low)
    extra = geo.find_extra(geo_low)
    near = geo.find_near(geo_low) if config.SEND_NEAR else []
    close = geo.find_close(geo_low)
    far = geo.find_far(geo_low)
    district = geo.find_district(geo_low)

    if not (zmiiv or close or district or extra or near):
        if friendly:
            places = [p for p in geo.find_close(geo_low)] or (
                ["Харківщина"] if geo.find_oblast(geo_low) else [])
            return {
                "level": "INFO",
                "reason": friendly[0],
                "places": places,
                "threats": [],
                "text": body,
                "key": dedup_key("INFO", places, [friendly[0]], body),
            }
        return None                     # дальний круг сам по себе — не повод

    # Новость про другую область, где Зміїв не при чём
    if not zmiiv and not close and geo.mentions_other_region(low):
        return None

    found = threats.detect_threats(low)

    # ГЛИБОКИЙ РОЗБІР. Канали пишуть списком, і тип загрози треба брати
    # саме з ТОГО рядка, де назване наше село:
    #     БпЛА від Борок на Таранівку     ← це наш рядок, це БпЛА
    #     FPV-дрон над Безруками
    #     БпЛА-розвідник біля Рубіжного   ← а це за 80 км
    # Раніше тип шукався по всьому тексту одразу, і Таранівці
    # діставався «розвідник» — просто тому, що він вище в таблиці типів.
    #
    # Застосовуємо лише до СПИСКІВ (два й більше пункти): звичайне
    # повідомлення з одного речення читається як і раніше.
    deep = None
    list_mode = False
    if config.SMART_READ:
        # Читаємо текст із живими рядками: список по пунктах у рядок —
        # звичайна форма повідомлень каналів.
        deep = reader.read(clean_lines(text))
        if len(deep["items"]) >= 2 and deep["ours"]:
            list_mode = True
            names = set(deep["types"])
            found = [(n, e) for n, e in found if n in names]

    threat_names = [n for n, _ in found]

    # У списку село-тезка визначається по СВОЄМУ рядку, а не по всьому
    # повідомленню: «на Андреевку, Садовод» у сусідньому рядку не
    # має «псувати» справжню Андріївку і навпаки.
    if deep and len(deep["items"]) >= 2 and near:
        item_near = {n for it in deep["items"] for n in it["near"]}
        near = [n for n in near if n in item_near]

    # FPV і «Ланцет» — фронтова зброя, до нашої глибини не долітає.
    # «FPV на Андріївку, Садовод» у зведенні по області — це майже напевно
    # ІНША Андріївка (їх багато), а не наша. Тому на ближньому поясі це
    # не «ціль курсом», а помітка: радар не впевнений і каже про це прямо.
    # Якщо FPV названо на саме місто чи ближнє село — це лишається серйозною
    # загрозою і йде звичайним шляхом нижче.
    if (config.SMART_READ and near and set(near) <= {"Андріївка"}
            and not (zmiiv or close or extra)
            and threat_names and set(threat_names) <= {"FPV", "Ланцет"}):
        place = ", ".join(near[:2])
        kind = threat_names[0]
        return {
            "level": "INFO",
            "reason": f"{kind}: ймовірно, не наша {place}",
            "places": near,
            "threats": threat_names,
            "text": body,
            "note": (f"{kind} — фронтова зброя, до нас не долітає. "
                     f"Назва «{place}» є в багатьох місцях області; у "
                     f"повідомленні немає нічого, що вказувало б саме на "
                     f"наше село. Радар вважає, що це НЕ наша "
                     f"{place}, але не впевнений — перевірте джерело."),
            "confidence": "low", "main_city": False, "near_home": False,
            "watch": True,
            "key": dedup_key("INFO", near, ["fpv-не-наше"], body),
        }

    # Артиллерия/обстрелы до Змієва не долетают — как признак воздушной
    # угрозы не годится. Разведывательные БпЛА и FPV тоже не повод будить:
    # они не бьют по городу. И то и другое даёт максимум MEDIUM.
    air = [t for t in found
           if t[0] != "Артилерія" and t[0] not in QUIET_TYPES]
    # «Розвідувальний БпЛА» містить обидва корені — «розвід» і «бпла».
    # Якщо названо розвідник або FPV, загальне «БпЛА» стосується його ж,
    # і будити через це не треба.
    # Власні типи: «тихі» не будять, «лише в закріплене» взагалі
    # не дають повідомлень
    custom = dict(threats.detect_custom(low))
    if custom and all(g == "pinned" for g in custom.values()) and not found:
        return None
    quiet_custom = {n for n, g in custom.items() if g in ("silent", "pinned")}
    if quiet_custom:
        air = [t for t in air if t[0] not in quiet_custom]

    if any(t[0] in QUIET_TYPES for t in found):
        air = [t for t in air if t[0] not in ("БпЛА", "Ціль")]

    course = threats.has_course(low)
    calm = threats.is_calm(low)
    impact = threats.is_impact(low)
    digest = is_digest(body)

    places = ([geo.main_name()] if zmiiv else []) + close + far + extra + near
    # Для підрахунку «масовості» far (Чугуїв і т.п.) не годиться: це
    # лише контекст, не наша ціль. Якщо взяти й Чугуїв, кількість
    # цілей САМЕ на нього могла б помилково піднімати тривогу по
    # Васищевому чи Зміїву.
    # Лише ті НП, що визначили рівень і причину сповіщення (у порядку
    # пріоритету гілок нижче): місто → ближні села → дальній пояс/додаткові
    # міста. Цифра з рядка про Чкаловське («3 на Шевченково, Чкаловское»)
    # не має ставати «3 шахеди на Васищеве» лише тому, що обидва пункти
    # є в одному повідомленні.
    if zmiiv:
        mass_places = [geo.main_name()]
    elif close:
        mass_places = list(close)
    else:
        mass_places = list(near) + list(extra)

    # --- Свої звуки / робота ППО -------------------------------------------
    if friendly and not (course and air):
        places = ([geo.main_name()] if zmiiv else []) + close
        return {
            "level": "INFO",
            "reason": friendly[0],
            "places": places,
            "threats": [],
            "text": body,
            "key": dedup_key("INFO", places, [friendly[0]], body),
        }

    # --- Отбой (проверяем первым: «відбій тривоги» содержит «тривога») -----
    if calm and not (course and air):
        if not (zmiiv or close or district):
            return None
        level, reason = "LOW", "відбій / чисто"

    # --- Розвідник або FPV: дивиться, але не б'є ---------------------------
    # Будити через це не треба, але знати корисно.
    elif found and not air and (zmiiv or close):
        level = "MEDIUM"
        reason = found[0][0].lower() + " над районом"

    # --- Прямая угроза Змієву ----------------------------------------------
    elif zmiiv and (air or (found and not digest)):
        level = "HIGH"
        reason = "підліт на Зміїв" if course else "загроза Змієву"

    elif zmiiv and course:
        # «Далее Змиев» — тип не назвали, но курс указан
        level, reason = "HIGH", "курс на Зміїв"

    # --- Подлёт через ближние сёла -----------------------------------------
    elif close and air and not digest:
        level = "HIGH" if config.HIGH_INCLUDES_NEIGHBORS else "MEDIUM"
        reason = "підліт через " + ", ".join(close[:3])

    # --- Средний уровень ----------------------------------------------------
    # Зведення («Протягом минулої доби ворожих ударів зазнали…») — це
    # ретроспектива: у ньому є і «прилетіло», і «Печеніги», і «Чугуїв»,
    # але це не наслідки прильоту, що сталися щойно. Без цієї перевірки
    # добова зведення ХОВА давала «ЧУГУЇВ · РАКЕТА · наслідки прильоту».
    elif (zmiiv or close or near) and impact and not has_digest_marker(body):
        level, reason = "MEDIUM", "наслідки прильоту"

    elif district and air and not digest:
        level, reason = "MEDIUM", "загроза по району"

    # Вибух чи приліт у нашому районі без назви міста — теж наша подія
    elif district and impact and not digest:
        level, reason = "MEDIUM", "наслідки прильоту в районі"

    elif close and course and config.SEND_NEAR and not digest and not air:
        level, reason = "MEDIUM", f"ціль курсом через {', '.join(close[:2])}"

    elif near and course and not digest and not (zmiiv or close):
        level, reason = "MEDIUM", f"ціль курсом на {', '.join(near[:2])}"

    elif near and air and course and not digest and not (zmiiv or close):
        level = "MEDIUM"
        reason = f"ціль поруч: {', '.join(near[:3])}"

    elif extra and air and not digest:
        level = "HIGH"
        reason = f"загроза: {', '.join(extra)}"

    elif zmiiv:
        level, reason = "MEDIUM", f"згадка: {geo.main_name()}"

    else:
        return None

    # У сводках числа ретроспективные («88 БпЛА за добу»), массовой
    # угрозой они не являются. Массовость считаем только по оперативным
    # сообщениям.
    # Якщо в тому ж повідомленні сказано «не фіксується» / «збито» —
    # це зняття, а не привід кричати повторами.
    # --- Наскільки радар упевнений -------------------------------------------
    # high   — названо і місто, і тип загрози: сумнівів немає
    # medium — місто назване, але тип не вказано, або загроза в сусідів
    # low    — висновок зроблено непрямо: район без міста, наслідки без
    #          типу, здогад за обстановкою. Такі повідомлення йдуть без
    #          звуку і з припискою «перевірте джерело».
    if digest:
        confidence = "low"          # зведення — це ретроспектива, не факт
    elif zmiiv and found:
        confidence = "high"
    elif (zmiiv and course) or (close and air):
        confidence = "medium"
    else:
        confidence = "low"

    mass = (mass_reason(clean_lines(text).lower(), threat_names, mass_places,
                        typed_here=list_mode)
            if level in ("HIGH", "MEDIUM") and not digest
            and confidence != "low" and not threat_gone(text) else None)

    # «Залп по Зміївському району» типу не називає, але це явно важче,
    # ніж поодинока ціль — піднімаємо до гучного рівня.
    if mass and level == "MEDIUM" and (zmiiv or district):
        level = "HIGH"
        reason = f"масована загроза: {mass}" if mass[0].isdigit() else mass

    # Последняя защита: сводка не может быть гучною, что бы в ней ни было.
    if digest and level == "HIGH":
        level = "MEDIUM"
        reason = "згадка у зведенні"
        mass = None

    # Ціль ВІДДАЛЯЄТЬСЯ: «від Змієва на Чугуїв» — вона вже пройшла над
    # нами й іде далі. Раніше це читалось так само, як «від Чугуєва на
    # Зміїв», і на кожен виліт від нас приходила зайва гучна тривога.
    if deep and deep.get("outgoing") and level == "HIGH":
        level = "MEDIUM"
        reason = f"ціль віддаляється від {geo.main_name()}"
        mass = None

    # Минулий час: «вночі вдарили», «за минулу добу». Знати корисно,
    # але будити повторами через те, що вже сталося, не можна.
    if config.SMART_READ and level == "HIGH" and retro_note(body):
        level = "MEDIUM"
        reason = "про минулі події: " + reason
        mass = None

    return {
        "level": level,
        "reason": reason,
        "places": places,
        "threats": found,
        "text": body,
        "mass_reason": mass if level == "HIGH" else None,
        "confidence": confidence,
        "count": int(mass.split()[0]) if mass and mass[0].isdigit() else 0,
        "main_city": bool(zmiiv),      # додаткові міста в закріплене не йдуть
        # Для добових лічильників: подія саме в місті або в нашому районі,
        # а не десь в області. Сусідні села теж рахуємо — це наша громада.
        "near_home": bool(zmiiv or district or close),
        # Зона, де приліт справді стосується нас: місто, його села,
        # Зміївська громада і найближчий пояс. Чугуїв і решта району —
        # ні, це 40 км. Через це в добовому звіті були зайві «прильоти».
        "impact_zone": bool(zmiiv or close or near
                            or geo.find_home_district(low)),
        "key": dedup_key(level, places, threat_names, body),
    }


def is_impact(low: str) -> bool:
    """Сообщение про уже случившийся прилёт (для суточного счётчика)."""
    return threats.is_impact(low)
