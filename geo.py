# --- Район и область ---------------------------------------------------------
# Зміїв с 2020 года входит в Чугуївський район Харківської області.
def _district_roots() -> list:
    return CITIES.district
OBLAST = ["харківськ", "харьковск", "харківщин", "харьковщин", "харків", "харьков"]

