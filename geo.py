# Назви напрямків фронту збігаються з назвами сіл:
# «На Південно-Слобожанському напрямку» — це ділянка фронту за сотні
# кілометрів, а не Слобожанське під Зміївом. Такі звороти вирізаємо
# ДО пошуку населених пунктів.
DIRECTION_RE = re.compile(
    r"[\w’'`\-]+\s+напрям\w*"          # «Слобожанському напрямку»
    r"|[\w’'`\-]+\s+направлени\w*"     # «Слобожанском направлении»
    r"|напрямку\s+[\w’'`\-]+",          # «напрямку Куп'янська»
    re.IGNORECASE)


def strip_directions(text: str) -> str:
    """Прибирає згадки напрямків фронту — вони не є географією загрози."""
    return DIRECTION_RE.sub(" ", text)


def _match(low: str, table: dict) -> list:
    """Ищет в тексте НП из таблицы. Возвращает список имён."""
    return [name for name, roots in table.items() if _has(low, roots)]


def find_close(low: str) -> list:
    """Ближние НП (подлёт на Зміїв). Напрямки фронту не рахуються."""
    return _match(strip_directions(low), CLOSE)


def find_far(low: str) -> list:
    """Дальние НП — только контекст."""
    return _match(strip_directions(low), FAR)


# Зміївська громада окремо від усього Чугуївського району:
# вибух у Чугуєві за 40 км нас не стосується.
ZMIIV_DISTRICT = ["зміївськ", "змиевск", "зміївська громада",
                  "зміївської громади", "змиевской громад"]


def find_home_district(low: str) -> bool:
    """Саме Зміївський район / громада, а не весь Чугуївський."""
    return _has(low, ZMIIV_DISTRICT)


def find_district(low: str) -> bool:
    """Упомянут ли район, за которым следит радар."""
    return _has(low, _district_roots())


def find_oblast(low: str) -> bool:
    """Упомянута ли Харьковская область."""
    return _has(low, OBLAST)


# Тревога объявляется по районам. Наш — Чугуївський (Зміїв входит в него
# с 2020 года). «Харківський район» — это другой район, западнее города,
# и к нам он отношения не имеет.
# «Харківщина» и связка «харківськ… област…» в любом падеже.
# Одного слова «Харківська» мало: «Харківська територіальна громада» —
# это город, а не область, и тревога там не наша.
OBLAST_ROOTS = ["харківськ", "харьковск"]
OBLAST_WORDS = ["област"]
OBLAST_ALONE = ["харківщин", "харьковщин", "по всій області", "вся область"]


def is_our_alarm_area(low: str) -> bool:
    """Относится ли объявление тревоги к Зміїву.

    Наши — Чугуївський/Зміївський район и объявления на всю область.
    Тревога по Харкову или Лозівському району к Зміїву отношения не имеет.
    """
    if _has(low, _district_roots()):
        return True
    if _has(low, OBLAST_ALONE):
        return True
    return _has(low, OBLAST_ROOTS) and any(w in low for w in OBLAST_WORDS)


def mentions_other_region(low: str) -> bool:
    """Сообщение про другую область — скорее всего не про нас."""
    return _has(low, OTHER_REGIONS)
