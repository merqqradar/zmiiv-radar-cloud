def find_near(low: str) -> list:
    """Ближний пояс. Учитывает слова-исключения для тёзок."""
    out = []
    for name, (roots, bad) in NEAR.items():
        if _has(low, roots) and not any(b in low for b in bad):
            out.append(name)
    return out


