def foreign_strike(text: str) -> str | None:
    """Новина про удар ПО ворогу або події на його території.

    Повертає короткий опис причини або None. Якщо наше місто в тексті
    названо — не спрацьовує: «шахеди з Бєлгорода на Зміїв» має
    залишитись тривогою.
    """
    low = (text or "").lower()
    if not low:
        return None
    # Названо наше місто, село чи найближчий пояс — це вже не «новина
    # про ворога». Вечірні зведення часто мішають одне з одним:
    # «вночі уражено НПЗ у рф» і поряд «вдарили по Печенігах».
    # Такі допис глушити не можна — про наші НП там сказано по ділу.
    if (geo.find_main(low) or geo.find_close(low) or geo.find_near(low)
            or geo.find_home_district(low)):
        return None
    if not any(w in low for w in _ENEMY_LAND):
        return None
    if any(w in low for w in _OUR_FORCES):
        return "новина про удар наших сил по території ворога"
    if any(w in low for w in _STRIKE_PAST):
        return "новина про події на території ворога"
    return None


