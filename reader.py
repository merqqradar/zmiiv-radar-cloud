# -*- coding: utf-8 -*-
"""Розумне читання повідомлень: розбір на пункти, прив'язка типу до місця.

НАВІЩО ЦЕ ПОТРІБНО

Канали пишуть не одну думку, а міні-звіт списком:

    ❗⚠️Харьковская область.
    БпЛА от Борки на Тарановку
    ⚠️FPV-дроны над Безруки
    ⚠️БпЛА-разведчик КВО🔄 севернее Рубежное

Старий розбір шукав типи загроз по ВСЬОМУ тексту одразу. Він бачив
«БпЛА», «FPV» і «разведчик» разом — і чіпляв до Таранівки той тип, що
стоїть вище в таблиці типів («Розвідувальний»), хоча над Таранівкою
летить БпЛА, а розвідник — за 80 км під Рубіжним. Так само в новині
«удар по нафтотерміналу Шесхаріс» слово «Калібр» з іншого речення
ставало «крилатою ракетою на Есхар».

Цей модуль ріже повідомлення на ПУНКТИ і читає кожен окремо: свій
тип, свої НП, свій напрямок. Тип беремо лише з того пункту, де
названо наше село, — або із заголовка («Шахеди:»), під яким пункт
стоїть.

Модуль нічого не вирішує сам: він лише читає. Рішення — у classify.py.
Вмикається перемикачем «Глибокий розбір» (settings: smart_read).
"""

import re

import geo
import threats

# --- Розрізання на пункти ----------------------------------------------------
# Маркери, якими канали відділяють пункти списку. 🔄 сюди НЕ входить:
# він означає «кружляє» і стоїть усередині пункту, а не між ними.
_MARKERS = ("⚠️", "⚠", "❗️", "❗", "⚡️", "⚡", "▪️", "▫️", "📍", "•",
            "🔴", "🟠", "🟡", "🟢", "🔵", "🟣", "🚀", "🛩", "🛸", "💣",
            "☄️", "🎯", "👁", "💥", "✈️", "➡️", "🔻", "—", "–")
_SPLIT_RE = re.compile("(?:" + "|".join(re.escape(m) for m in _MARKERS)
                       + r"|[\n\r]+)+")

# Напрямок руху. «від Змієва на Чугуїв» — ціль ВІДДАЛЯЄТЬСЯ,
# «від Чугуєва на Зміїв» — НАБЛИЖАЄТЬСЯ. Раніше обидва читались
# однаково, і на кожен виліт від нас приходила зайва тривога.
_FROM_RE = re.compile(r"(?<!\w)(?:від|от|з-під|из-под|зі|со)\s+")
_TO_RE = re.compile(r"(?<!\w)(?:на|до|курсом на|курс на|у бік|в бік|"
                    r"в сторону|у напрямку|в напрямку)\s+")
_CIRCLE_RE = re.compile(r"🔄|кружл|кружит|між|между|барраж")


def _header_of(chunk: str):
    """Ділить пункт на (зміст, заголовок-тип).

    «2 на Городнє, Гути FPV-дрони:» → зміст «2 на Городнє, Гути»,
    заголовок «FPV». Заголовок діє на наступні пункти, доки не
    зміниться. Саме так канали й пишуть: спочатку «Шахеди:» і список,
    потім «FPV-дрони:» і вже інший список.
    """
    stripped = chunk.rstrip()
    if not stripped.endswith(":"):
        return chunk, None
    before = stripped[:-1]
    hits = threats.find_types_with_pos(before.lower())
    if not hits:
        return chunk, None
    # Між назвою типу і двокрапкою не має бути інших слів, інакше це
    # не заголовок, а звичайне речення, що випадково скінчилось на «:».
    tail = [h for h in hits if h[2] >= len(before) - 2]
    if not tail:
        return chunk, None
    # «FPV-дрони» — це ОДНА назва, у якій два корені («fpv» і «дрон»).
    # Беремо початок найранішого з них поруч, інакше заголовок
    # прочитається як «БпЛА» і весь список піде з чужим типом.
    last_start = tail[-1][1]
    start = min(h[1] for h in hits if h[1] >= last_start - 14)
    phrase = before[start:]
    if len(phrase) > 26:
        return chunk, None
    named = threats.detect_threats(phrase.lower())
    if not named:
        return chunk, None
    return before[:start], named[0][0]


def _role(low: str, roots) -> str:
    """Як НП згадано в пункті: 'to' (на нього), 'from' (від нього), ''.

    Прийменник шукаємо в ПОВНОМУ тексті пункту, а не в обрізаному
    шматку перед назвою: обрізання створювало фальшивий початок слова,
    і в «Тот что Эсхар, далее Змиев» хвіст «от» зі слова «Тот»
    читався як прийменник «от» — ціль нібито летіла ВІД Змієва.
    """
    match = geo._pattern(tuple(roots)).search(low)
    if not match:
        return ""
    pos = match.start()

    def last_before(rx):
        best = None
        for m in rx.finditer(low):
            if m.end() <= pos and pos - m.end() <= 20:
                best = m.end()
        return best

    last_from = last_before(_FROM_RE)
    last_to = last_before(_TO_RE)
    if last_from is None and last_to is None:
        return ""
    if last_to is None:
        return "from"
    if last_from is None:
        return "to"
    return "to" if last_to > last_from else "from"


def items(text: str) -> list:
    """Розбирає повідомлення на пункти. Кожен пункт читається окремо."""
    out = []
    header = None
    last_type = None
    for raw in _SPLIT_RE.split(text or ""):
        content, new_header = _header_of(raw)
        content = content.strip(" .,;·-")
        if content:
            low = content.lower()
            own = [n for n, _e in threats.detect_threats(low)]
            # Тип, названий ВИЩЕ по тексту, діє на пункти без свого типу.
            # Саме так канали й пишуть:
            #     **Бандеролі в області**
            #     ▪️1 на Зміїв        ← це теж бандероль
            #     ▪️1 на Берестин
            # Без успадкування рядок «1 на Зміїв» лишався зовсім без
            # типу, і гучна тривога падала до звичайної згадки міста.
            if own:
                last_type = own[0]
            out.append({
                "text": content,
                "types": own or ([last_type] if last_type else []),
                "own_types": own,
                "header": header,
                "main": geo.find_main(low),
                "close": geo.find_close(low),
                "near": geo.find_near(low),
                "far": geo.find_far(low),
                "extra": geo.find_extra(low),
                "district": geo.find_district(low),
                "other_region": geo.mentions_other_region(low),
                "main_role": _role(low, geo.CITIES.main),
                "circling": bool(_CIRCLE_RE.search(low)),
            })
        if new_header:
            header = new_header
            last_type = new_header
    return out


def read(text: str) -> dict:
    """Читає повідомлення як список пунктів і виділяє НАШІ.

    Повертає:
        items    — усі пункти
        ours     — лише ті, де названо наше місто / село / район
        types    — типи загроз САМЕ з наших пунктів (а не з усього тексту)
        outgoing — ціль іде ВІД нашого міста, а не на нього
    """
    parsed = items(text)
    ours = [it for it in parsed
            if it["main"] or it["close"] or it["near"] or it["extra"]
            or it["district"]]
    types = []
    for it in ours:
        for name in it["types"]:
            if name not in types:
                types.append(name)

    # Ціль віддаляється: у пункті наше місто стоїть після «від», а
    # напрямок «на» вказує на чуже. Тоді це не підліт, а відліт.
    outgoing = bool(ours) and all(
        it["main_role"] == "from" for it in ours if it["main"]) and any(
        it["main"] for it in ours)

    return {"items": parsed, "ours": ours, "types": types,
            "outgoing": outgoing,
            "circling": any(it["circling"] for it in ours)}


