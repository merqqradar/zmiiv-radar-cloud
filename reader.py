def retrospective(text: str) -> str | None:
    """Повідомлення про те, що вже сталося. Повертає опис або None."""
    low = (text or "").lower()
    if not low:
        return None
    if any(t in low for t in _PAST_TIME) and any(v in low for v in _PAST_VERB):
        return "повідомлення про минулі події"
    return None


# --- Міні-звіт по області -----------------------------------------------------
# Канали раз на кілька хвилин дають ПОВНИЙ зріз: усе, що зараз летить
# по області. Якщо в новому зрізі нашої цілі вже немає — її вже немає,
# і чекати 10 хвилин тиші, щоб це зрозуміти, не треба.
_REPORT_HEAD = ["харківська область", "харьковская область", "харківщина",
                "харьковщина", "по області", "по области", "обстановка по",
                "ситуація по", "ситуация по"]


# Число на початку пункту: «2 в районі Великої Писарівки» — це дві цілі.
_COUNT_AT_START = re.compile(r"^\D{0,3}(\d{1,2})(?!\d)")


def area_targets(text: str) -> list:
    """Скільки цілей і яких у зведенні по області.

    «Харківська область. Шахеди: ⚠️на Богодухів ⚠️2 в районі Великої
    Писарівки» — це ТРИ шахеди, а не нуль.

    Раніше обстановку по області рахувала лише oblast_rockets(), яка
    бере до уваги самі ракети, та ще й від трьох штук. Через це в
    закріпленому чесно писалось «Цілей в області: 0» тоді, коли по
    області йшли шахеди — просто вони в той підрахунок не потрапляли.
    """
    out = []
    for item in items(text):
        if not item["types"]:
            continue                    # шапка або рядок без типу
        match = _COUNT_AT_START.match(item["text"])
        count = int(match.group(1)) if match else 1
        out.append({"kind": item["types"][0], "count": min(count, 20),
                    "text": item["text"][:60]})
    return out


def area_report(text: str) -> dict | None:
    """Зріз обстановки по області. Повертає {'places', 'types'} або None.

    Це саме ПЕРЕЛІК цілей (два і більше пункти з НП), а не одна згадка
    області в звичайному повідомленні.
    """
    low = (text or "").lower()
    if not low:
        return None
    head = low[:80]
    if not any(h in head for h in _REPORT_HEAD):
        return None
    parsed = items(text)
    # Зріз — це ПЕРЕЛІК цілей: два і більше пункти, у кожному названо
    # тип. Одна згадка області у звичайному дописі зрізом не є.
    listed = [it for it in parsed if it["types"]]
    if len(listed) < 2:
        return None

    places, types = set(), set()
    for it in parsed:
        if it["main"]:
            places.add(geo.main_name())
        for name in it["close"] + it["near"] + it["far"] + it["extra"]:
            places.add(name)
        types.update(it["types"])
    return {"places": places, "types": types, "count": len(listed)}
