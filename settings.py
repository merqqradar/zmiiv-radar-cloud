def load() -> dict:
    """Читает настройки, подставляя значения по умолчанию."""
    values = dict(DEFAULTS)
    if SETTINGS_FILE.exists():
        try:
            saved = json.loads(SETTINGS_FILE.read_text(encoding="utf-8"))
            # Заготовки міст підставляємо, якщо поле порожнє: так
            # Харків і Київ з'являються у вже створеному файлі налаштувань.
            prefill = {"city_2_name", "city_2_variants",
                       "city_3_name", "city_3_variants"}
            for key in DEFAULTS:
                if key in saved:
                    if key in prefill and not str(saved[key]).strip():
                        continue
                    values[key] = saved[key]
        except (json.JSONDecodeError, ValueError):
            pass                    # битый файл — работаем на умолчаниях

    # Змінна середовища для хмарного розгортання: дозволяє задати роль
    # (наприклад "backup") через панель Railway, не чіпаючи settings.json
    # локального застосунку. Ніяк не впливає на десктоп-версію — там
    # ця змінна просто не виставлена.
    env_role = os.environ.get("RADAR_ROLE")
    if env_role in ("main", "backup"):
        values["role"] = env_role

    # Налаштування, надіслані кнопкою «Синхронізувати налаштування» з
    # застосунку. Застосовуються один раз: мітка _synced_at, збережена
    # тут-таки на диск, не дає повторно накочувати ті самі (вже застарілі)
    # значення при кожному наступному перезапуску контейнера.
    pushed = os.environ.get("RADAR_SETTINGS_JSON")
    if pushed:
        try:
            incoming = json.loads(pushed)
        except (json.JSONDecodeError, ValueError):
            incoming = None
        if isinstance(incoming, dict) and incoming.get("_synced_at") and \
                incoming["_synced_at"] != values.get("_synced_at"):
            for key, val in incoming.items():
                if key in DEFAULTS and key not in SYNC_EXCLUDE:
                    values[key] = val
            values["_synced_at"] = incoming["_synced_at"]
            save(values)

    return values


def save(values: dict) -> None:
    """Сохраняет настройки. Пишет только известные ключи."""
    DATA_DIR.mkdir(exist_ok=True)
    clean = {k: values[k] for k in DEFAULTS if k in values}
    SETTINGS_FILE.write_text(json.dumps(clean, ensure_ascii=False, indent=2),
                             encoding="utf-8")
