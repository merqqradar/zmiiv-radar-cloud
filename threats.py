    ("Швидкісна ціль", "🎯", ["ціль", "цілі", "цiль", "цель", "цели", "цілей",
                              "швидкісна ціль", "скоростная цель"]),
    ("Артилерія",      "💥", ["артил", "рсзв", "рсзо", "град", "смерч", "ураган",
                              "мінометн", "миномет", "обстріл", "обстрел"]),
