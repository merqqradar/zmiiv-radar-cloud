"""Типы воздушных угроз и сленг, которым пользуются каналы.

Сленг — не выдумка, он взят из выгрузки за 30 дней:
"реактив", "бандероль", "мопед", "італмас", "Р. Шахед" — это всё дроны.
Без него фильтр пропускает примерно половину сообщений про Зміїв.

Порядок в списке важен: чем выше, тем приоритетнее при определении типа.
"""

