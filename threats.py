# Слова, означающие ДВИЖЕНИЕ угрозы в сторону цели.
# "Далее Змиев", "взял курс на Змиев", "у напрямку Змієва" — это подлёт.
COURSE_MARKERS = [
    "курс на", "курсом на", "взял курс", "далее", "далі", "у напрямку",
    "в напрямку", "напрямок", "напрямку", "рухається", "движется", "летить",
    "летит", "прямує", "в бік", "в сторону", "на підході", "на подходе",
    "заходить", "заходит", "кружит", "кружляє", "повз", "над",
    # «Від Печенігів через Коробочкине на Андріївку» — теж рух
    "через", "від ", "от ", "мимо", "повз ",
]

# Отбой / спокойно.
CALM_MARKERS = [
    "відбій", "отбой", "чисто", "свої", "свои", "не фіксується",
    "не фиксируется", "не наблюдается", "не спостерігається",
    "загроза минула", "угроза миновала",
]

# Последствия (прилёт уже был) — это не предупреждение, но важно.
IMPACT_MARKERS = [
    "прилі", "прилет", "влучан", "вибух", "взрыв", "пошкоджен",
    "повреждён", "повреждено", "постраждал", "пострадал", "загинул", "погиб",
]


# Короткие корни, которые обязаны стоять в НАЧАЛЕ слова.
# Иначе "град" ловится в Павлограде и Краснограде, "каб" — в "кабель",
# "цель" — в "прицельно", "танк" — в "танкер".
BOUNDED = {"град", "каб", "каби", "кабы", "цель", "цели", "ціль", "цілі",
           "цiль", "цілей", "танк", "зала", "бомб", "пуск", "міг", "миг",
           "смерч", "ураган", "мопед", "реактив", "реактивн"}

_COMPILED = [
    (name, emoji, re.compile("|".join(
        (r"\b" + re.escape(r)) if r in BOUNDED else re.escape(r)
        for r in roots)))
    for name, emoji, roots in THREAT_TYPES
]


def _parse_custom(raw: str) -> list:
    """Розбирає поле «Назва: корінь, корінь» на список типів."""
    out = []
    for line in (raw or "").splitlines():
        if ":" not in line:
            continue
        name, roots = line.split(":", 1)
        roots = [r.strip().lower() for r in roots.split(",") if r.strip()]
        if name.strip() and roots:
            out.append((name.strip(), roots))
    return out


def custom_types() -> dict:
    """Власні типи з налаштувань: {назва: (група, корені)}."""
    import config

    table = {}
    for group, raw in (("loud", config.TYPES_LOUD),
                       ("silent", config.TYPES_SILENT),
                       ("pinned", config.TYPES_PINNED)):
        for name, roots in _parse_custom(raw):
            table[name] = (group, roots)
    return table


def builtin_as_text() -> tuple:
    """Вбудовані типи у форматі полів налаштувань: (гучні, тихі)."""
    quiet = {"Розвідувальний"}
    loud, silent = [], []
    for name, _emoji, roots in THREAT_TYPES:
        line = f"{name}: {', '.join(roots)}"
        (silent if name in quiet else loud).append(line)
    return "\n".join(loud), "\n".join(silent)


def detect_custom(low: str) -> list:
    """Знайдені власні типи: [(назва, група)]."""
    return [(name, group) for name, (group, roots) in custom_types().items()
            if any(root in low for root in roots)]


def detect_threats(low: str) -> list:
    """Возвращает список найденных типов угроз: [(имя, эмодзи), ...]."""
    import config

    # Власні типи попереду вбудованих: користувач знає краще
    found = [(name, "🎯" if group != "silent" else "👁")
             for name, group in detect_custom(low)]
    if config.TYPES_REPLACE and custom_types():
        return found            # вбудовані вимкнені — працюють лише свої
    return found + [(name, emoji) for name, emoji, rx in _COMPILED
                    if rx.search(low)]


def find_types_with_pos(low: str) -> list:
    """Знайдені типи разом із позицією в тексті: [(назва, початок, кінець)].

    Потрібно розумному читанню (reader.py), щоб зрозуміти, до ЯКОГО
    пункту списку належить тип: «Шахеди: ... FPV-дрони: ...» — усе, що
    після другого заголовка, це вже FPV, а не шахеди.
    """
    out = []
    for name, _emoji, rx in _COMPILED:
        for m in rx.finditer(low):
            out.append((name, m.start(), m.end()))
    out.sort(key=lambda t: t[1])
    return out


# Маркери теж шукаємо ПО МЕЖІ СЛОВА. Без цього «Чистоводовка»
# читалась як «чисто» (тобто відбій) і глушила справжню ціль.
#
# Більшість маркерів — це КОРЕНІ, у яких змінюється закінчення
# («пошкоджен-о/-ий», «прилет-ів/-іла»), тому справа межу не ставимо.
# А ось ці — цілі слова, і саме вони й давали хибні збіги:
#   «чисто»  у «Чистоводовка»   → фальшивий відбій
#   «над»    у «Надія», «надійшло»
#   «мимо»   у «мимохідь»
_WHOLE_WORDS = {"чисто", "свої", "свои", "над", "повз", "мимо"}


def _bounded(words):
    return re.compile("|".join(
        r"(?<!\w)" + re.escape(w) + (r"(?!\w)" if w in _WHOLE_WORDS else "")
        for w in words))


_COURSE_RE = _bounded(COURSE_MARKERS)
_CALM_RE = _bounded(CALM_MARKERS)
_IMPACT_RE = _bounded(IMPACT_MARKERS)


def has_course(low: str) -> bool:
    """Есть ли признак движения угрозы в сторону цели."""
    return bool(_COURSE_RE.search(low))


def is_calm(low: str) -> bool:
    """Сообщение про отбой / отсутствие угрозы."""
    return bool(_CALM_RE.search(low))


def is_impact(low: str) -> bool:
    """Сообщение про уже случившийся прилёт."""
    return bool(_IMPACT_RE.search(low))
